"""Export the vanilla KKS neutral body and head as one schema-compatible pair.

The character PNG does not contain either shared mesh.  The game instantiates
these skinned renderers and drives them with the native ``cf_*`` skeleton. This
offline command keeps that boundary intact: it never starts the game or bakes
a character's shape into the shared assets. Body and head are staged together
and their manifests are published last so the current material schema cannot be half-generated by
a failed conversion.
"""

from __future__ import annotations

import argparse
import json
import os
import tempfile
from pathlib import Path
from typing import Any

import UnityPy  # type: ignore

from kks_runtime_skin_export import (
    HIERARCHY_SCHEMA_VERSION,
    MATERIAL_SCHEMA_VERSION,
    _convert_environment,
    _prefab_hierarchy_payload,
    _renderer_payload,
)


def _body_renderer_offset(renderer: Any) -> list[float]:
    """Return the authored oo_base placement used by the native body shell."""

    offset = [0.0, 0.0, 0.0]
    try:
        transform = next(
            component.component.read()
            for component in renderer.m_GameObject.read().m_Component
            if getattr(component, "component", None)
            and component.component.read().__class__.__name__ == "Transform"
        )
        # oo_base places the body under cf_o_root (the native body root is
        # translated upward by 1.1435 Unity units). Preserve that placement;
        # omitting it makes the otherwise correct body sit below the face.
        chain = []
        while transform:
            chain.append(transform)
            transform = transform.m_Father.read() if getattr(transform, "m_Father", None) else None
        for node in reversed(chain):
            pos = node.m_LocalPosition
            offset = [offset[i] + float(pos[i]) for i in range(3)]
    except Exception:
        pass
    if abs(offset[1]) < 1e-6:
        # oo_base's body roots are authored at this fixed native placement;
        # Unity's serialized transform can be unresolved when the bundle is
        # opened without its external CAB sidecar.
        offset[1] = 1.1435
    return offset


def export_renderer(
    renderer: Any,
    texture_path: Path | None = None,
    *,
    image_cache: dict[tuple[int, int, int], Any | None] | None = None,
) -> dict[str, Any] | None:
    """Export one neutral body renderer with the current runtime material contract.

    The runtime converter remains the single implementation of mesh normals,
    skin normalization and shader semantics.  The native-base exporter adds
    only oo_base's shared-shell placement and source identity.
    """

    payload = _renderer_payload(renderer, texture_path, image_cache=image_cache)
    if payload is None:
        return None
    payload["position"] = _body_renderer_offset(renderer)
    payload["source"] = "Koikatu Sunshine oo_base.unity3d:o_body_a"
    return payload


def _load_with_sibling_dependencies(primary: Path, sibling_names: tuple[str, ...]) -> Any:
    if not primary.is_file():
        raise FileNotFoundError(f"bundle {primary} does not exist")
    candidates = [primary, *(primary.with_name(name) for name in sibling_names)]
    return UnityPy.load(*(str(path) for path in candidates if path.is_file()))


def _find_named_game_object(environment: Any, name: str) -> Any:
    for obj in environment.objects:
        if obj.type.name != "GameObject":
            continue
        try:
            game_object = obj.read()
        except Exception:
            continue
        if str(getattr(game_object, "m_Name", "") or "") == name:
            return game_object
    raise ValueError(f"GameObject {name!r} was not found in the loaded bundles")


def _atomic_write_json(path: Path, payload: Any, *, indent: int | None = None) -> None:
    """Durably replace one JSON file without exposing a partial document."""

    path.parent.mkdir(parents=True, exist_ok=True)
    temporary_name = ""
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            prefix=f".{path.name}.",
            suffix=".tmp",
            dir=path.parent,
            delete=False,
        ) as temporary:
            temporary_name = temporary.name
            json.dump(
                payload,
                temporary,
                ensure_ascii=False,
                indent=indent,
                separators=None if indent is not None else (",", ":"),
            )
            temporary.flush()
            os.fsync(temporary.fileno())
        os.replace(temporary_name, path)
    finally:
        if temporary_name:
            Path(temporary_name).unlink(missing_ok=True)


def _safe_dependency_name(value: Any) -> str:
    name = str(value or "").replace("\\", "/")
    relative = Path(name)
    if not name or relative.is_absolute() or ".." in relative.parts:
        raise ValueError(f"unsafe runtime dependency path {name!r}")
    return name


def _runtime_files(payload: dict[str, Any], root: Path) -> list[dict[str, Any]]:
    names = {
        _safe_dependency_name(material[field])
        for material in payload.get("materials", [])
        if isinstance(material, dict)
        for field in ("texture", "colorMask", "normalTexture", "alphaMask")
        if material.get(field)
    }
    result: list[dict[str, Any]] = []
    for name in sorted(names):
        dependency = root / name
        if not dependency.is_file():
            raise ValueError(f"runtime dependency {name!r} was not generated")
        result.append({"name": name, "size": dependency.stat().st_size, "kind": "png"})
    return result


def _validate_material_contract(payload: dict[str, Any], source: str) -> None:
    vertices = payload.get("vertices")
    normals = payload.get("normals")
    if not isinstance(vertices, list) or not vertices:
        raise ValueError(f"{source} has no vertices")
    if not isinstance(normals, list) or len(normals) != len(vertices):
        raise ValueError(f"{source} has no complete authored normals")
    for index, material in enumerate(payload.get("materials", [])):
        if not isinstance(material, dict) or not material.get("materialResolved"):
            continue
        missing = {
            field
            for field in ("shaderFamily", "alphaMode", "depthWrite", "transparentWithZWrite")
            if field not in material
        }
        if missing:
            raise ValueError(
                f"{source} material {index} is missing schema-{MATERIAL_SCHEMA_VERSION} fields {sorted(missing)}"
            )


def _stage_neutral_body(bundle: Path, output: Path) -> list[dict[str, Any]]:
    # oo_base references its vanilla body materials through shared CAB data in
    # mm_base/bo_head_00. Loading only oo_base leaves material PPtrs dangling
    # and produces the flat-grey body that prompted this exporter.
    environment = _load_with_sibling_dependencies(
        bundle,
        ("mm_base.unity3d", "bo_head_00.unity3d"),
    )
    body_root = _find_named_game_object(environment, "p_cf_body_bone")
    hierarchy = _prefab_hierarchy_payload(body_root)
    if not hierarchy.get("names"):
        raise ValueError("p_cf_body_bone hierarchy is empty")
    hierarchy_name = "hierarchy.json"
    hierarchy_path = output / hierarchy_name
    _atomic_write_json(hierarchy_path, hierarchy)
    hierarchy_size = hierarchy_path.stat().st_size

    items: list[dict[str, Any]] = []
    image_cache: dict[tuple[int, int, int], Any | None] = {}
    for obj in environment.objects:
        if obj.type.name != "SkinnedMeshRenderer":
            continue
        try:
            renderer = obj.read()
            game_object = renderer.m_GameObject.read()
            if str(getattr(game_object, "m_Name", "") or "") != "o_body_a":
                continue
            # oo_base contains male/female and high/low LOD alternatives with
            # the same GameObject name. Only cf_m_body is the female full-LOD
            # shell; stacking its siblings recreates the overlapping torso.
            material_names: list[str] = []
            for pointer in getattr(renderer, "m_Materials", ()) or ():
                try:
                    material_names.append(str(pointer.read().m_Name))
                except Exception:
                    continue
            if "cf_m_body" not in material_names:
                continue
            index = len(items)
            filename = f"body-{index:02d}.json"
            target = output / filename
            payload = export_renderer(
                renderer,
                target.with_name(f"body-{index:02d}-tex.png"),
                image_cache=image_cache,
            )
            if payload is None:
                continue
            _validate_material_contract(payload, filename)
            _atomic_write_json(target, payload)
            item: dict[str, Any] = {
                "id": f"neutral-body-{index:02d}",
                "runtimeSkin": filename,
                "runtimeSkinSize": target.stat().st_size,
                "runtimeHierarchy": hierarchy_name,
                "runtimeHierarchySize": hierarchy_size,
                "position": payload["position"],
                "skinned": True,
                "rigidAttachment": False,
                "rendererEnabled": bool(getattr(renderer, "m_Enabled", 1)),
                "gameObjectActive": bool(getattr(game_object, "m_IsActive", 1)),
                "source_kind": "neutral_body",
                "runtimeFiles": _runtime_files(payload, output),
            }
            if payload.get("texture"):
                texture_name = _safe_dependency_name(payload["texture"])
                texture_path = output / texture_name
                item["texture"] = texture_name
                item["textureSize"] = texture_path.stat().st_size
            items.append(item)
        except Exception as exc:
            raise ValueError(f"failed to export body renderer {getattr(obj, 'path_id', '?')}: {exc}") from exc

    if len(items) != 1:
        raise ValueError(f"expected exactly one female full-LOD body renderer, found {len(items)}")
    manifest = {
        "version": 2,
        "materialSchemaVersion": MATERIAL_SCHEMA_VERSION,
        "hierarchySchemaVersion": HIERARCHY_SCHEMA_VERSION,
        "runtimeHierarchy": hierarchy_name,
        "items": items,
    }
    _atomic_write_json(output / "manifest.json", manifest, indent=2)
    return items


def _stage_neutral_head(bundle: Path, output: Path, main_data: str) -> list[dict[str, Any]]:
    # Keep the selected head on the exact same converter/material semantics as
    # card-owned heads. Dependencies are loaded only for this explicit offline
    # command; no runtime request performs Unity extraction.
    environment = _load_with_sibling_dependencies(
        bundle,
        ("mm_base.unity3d", "oo_base.unity3d"),
    )
    items = _convert_environment(environment, main_data, output)
    if not items:
        raise ValueError(f"neutral head {main_data!r} exported no renderers")
    return items


def _validate_staged_manifest(root: Path) -> dict[str, Any]:
    manifest_path = root / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if (
        manifest.get("version") != 2
        or manifest.get("materialSchemaVersion") != MATERIAL_SCHEMA_VERSION
        or manifest.get("hierarchySchemaVersion") != HIERARCHY_SCHEMA_VERSION
    ):
        raise ValueError(
            f"{manifest_path} does not use runtime manifest/material/hierarchy "
            f"schema 2/{MATERIAL_SCHEMA_VERSION}/{HIERARCHY_SCHEMA_VERSION}"
        )
    items = manifest.get("items")
    if not isinstance(items, list) or not items:
        raise ValueError(f"{manifest_path} contains no runtime items")
    for item in items:
        if not isinstance(item, dict) or not isinstance(item.get("runtimeFiles"), list):
            raise ValueError(f"{manifest_path} contains a legacy item without runtimeFiles")
        for field, size_field in (
            ("runtimeSkin", "runtimeSkinSize"),
            ("runtimeHierarchy", "runtimeHierarchySize"),
        ):
            name = _safe_dependency_name(item.get(field))
            path = root / name
            if not path.is_file() or item.get(size_field) != path.stat().st_size:
                raise ValueError(f"{manifest_path} has an invalid {field}/{size_field} pair")
            if field == "runtimeSkin":
                skin_payload = json.loads(path.read_text(encoding="utf-8"))
                if not isinstance(skin_payload, dict) or skin_payload.get("version") != 2:
                    raise ValueError(f"{path} is not a runtime skin version 2 payload")
                _validate_material_contract(skin_payload, name)
        for dependency in item["runtimeFiles"]:
            if not isinstance(dependency, dict):
                raise ValueError(f"{manifest_path} contains an invalid runtimeFiles entry")
            name = _safe_dependency_name(dependency.get("name"))
            path = root / name
            if not path.is_file() or dependency.get("size") != path.stat().st_size:
                raise ValueError(f"{manifest_path} has an invalid runtimeFiles size for {name}")
    return manifest


def _publish_staged_pair(staged_outputs: tuple[tuple[Path, Path], ...]) -> None:
    """Publish dependencies for both assets, then atomically replace manifests."""

    for staging, destination in staged_outputs:
        destination.mkdir(parents=True, exist_ok=True)
        for source in sorted(path for path in staging.rglob("*") if path.is_file()):
            relative = source.relative_to(staging)
            if relative.as_posix() == "manifest.json":
                continue
            target = destination / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            os.replace(source, target)
    # Both complete asset sets now exist. Each manifest replacement is atomic,
    # and no manifest is exposed until both conversions and validations pass.
    for staging, destination in staged_outputs:
        os.replace(staging / "manifest.json", destination / "manifest.json")


def export_shared_pair(
    *,
    body_bundle: Path,
    body_output: Path,
    head_bundle: Path,
    head_output: Path,
    head_main_data: str = "p_cf_head_00",
) -> dict[str, Any]:
    if body_output.resolve() == head_output.resolve():
        raise ValueError("body and head outputs must be different directories")
    body_output.parent.mkdir(parents=True, exist_ok=True)
    head_output.parent.mkdir(parents=True, exist_ok=True)
    with (
        tempfile.TemporaryDirectory(prefix=f".{body_output.name}-", dir=body_output.parent) as body_temp,
        tempfile.TemporaryDirectory(prefix=f".{head_output.name}-", dir=head_output.parent) as head_temp,
    ):
        staged_body = Path(body_temp)
        staged_head = Path(head_temp)
        body_items = _stage_neutral_body(body_bundle, staged_body)
        head_items = _stage_neutral_head(head_bundle, staged_head, head_main_data)
        _validate_staged_manifest(staged_body)
        _validate_staged_manifest(staged_head)
        _publish_staged_pair(((staged_body, body_output), (staged_head, head_output)))
    return {
        "materialSchemaVersion": MATERIAL_SCHEMA_VERSION,
        "hierarchySchemaVersion": HIERARCHY_SCHEMA_VERSION,
        "body": {"output": str(body_output), "items": len(body_items)},
        "head": {"output": str(head_output), "items": len(head_items), "mainData": head_main_data},
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Offline-export the native KKS neutral body/head pair with runtime schema "
            f"2/{MATERIAL_SCHEMA_VERSION}/{HIERARCHY_SCHEMA_VERSION}."
        )
    )
    parser.add_argument("--body-bundle", type=Path, required=True, help="abdata/chara/oo_base.unity3d")
    parser.add_argument("--body-output", type=Path, required=True, help="neutral-body output directory")
    parser.add_argument("--head-bundle", type=Path, required=True, help="abdata/chara/bo_head_00.unity3d")
    parser.add_argument("--head-output", type=Path, required=True, help="neutral-head output directory")
    parser.add_argument("--head-main-data", default="p_cf_head_00", help="vanilla neutral head prefab")
    args = parser.parse_args()
    result = export_shared_pair(
        body_bundle=args.body_bundle,
        body_output=args.body_output,
        head_bundle=args.head_bundle,
        head_output=args.head_output,
        head_main_data=args.head_main_data,
    )
    print(json.dumps(result, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
