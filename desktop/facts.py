"""Validated offline overview content.

The catalog is an optional packaged asset. It is treated as untrusted input:
malformed, duplicated, or self-attributed catalogs are rejected and a tiny
conservative fallback is used. Cards never participate in plan or map state.
"""

from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path
from typing import Any, Iterable

_FALLBACK_FACTS = (
    ("科学方法", "可重复的观察和实验有助于检验解释。", "来源：开放科学常识"),
    ("统计", "平均数容易受极端值影响，中位数通常更稳健。", "来源：统计学基础"),
    ("安全", "处理重要信息前，先确认来源和上下文可以减少误解。", "来源：信息素养基础"),
)
_SELF_ATTRIBUTION_RE = re.compile(
    r"mentorflow|离线知识卡|通用常识|本地知识|generated by|自生成|self[- ]?attributed",
    re.IGNORECASE,
)


def _catalog_candidates() -> tuple[Path, ...]:
    roots: list[Path] = []
    frozen_root = getattr(sys, "_MEIPASS", None)
    if frozen_root:
        roots.append(Path(frozen_root))
    source_root = Path(__file__).resolve().parents[1]
    roots.extend((source_root, source_root / "package", Path.cwd()))
    candidates: list[Path] = []
    for root in roots:
        candidates.extend(
            (
                root / "content" / "knowledge_cards" / "offline_facts.v1.json",
                root / "package" / "content" / "knowledge_cards" / "offline_facts.v1.json",
            )
        )
    return tuple(dict.fromkeys(path.resolve() for path in candidates))


def _entries(payload: Any) -> Iterable[Any]:
    if isinstance(payload, list):
        return payload
    if isinstance(payload, dict):
        for key in ("entries", "facts", "items", "cards"):
            value = payload.get(key)
            if isinstance(value, list):
                return value
    return ()


def _text(item: dict[str, Any], *keys: str) -> str:
    for key in keys:
        value = item.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()
    return ""


def validate_catalog(payload: Any, *, minimum: int = 200) -> tuple[tuple[str, str, str], ...]:
    """Validate and normalize a catalog, raising ``ValueError`` on failure."""

    normalized: list[tuple[str, str, str]] = []
    seen: set[tuple[str, str]] = set()
    for raw in _entries(payload):
        if not isinstance(raw, dict):
            raise ValueError("offline facts catalog contains a non-object entry")
        title = _text(raw, "title", "topic", "heading")
        body = _text(raw, "body", "fact", "summary", "text", "description")
        source_value = raw.get("source")
        if isinstance(source_value, dict):
            source = _text(source_value, "name", "title", "publisher", "source_name")
            source_url = _text(source_value, "url", "link", "source_url")
        else:
            source = _text(raw, "source", "source_name", "official_source", "publisher")
            source_url = _text(raw, "source_url", "url", "link", "official_url")
            if source.startswith("https://") and not source_url:
                source_url, source = source, "官方来源"
        attribution = f"{source or '官方来源'} · {source_url}" if source_url else source
        if not title or not body or not source or not source_url:
            raise ValueError("offline facts catalog entries require title, body, source and source_url")
        if _SELF_ATTRIBUTION_RE.search(f"{source} {source_url} {title} {body}"):
            raise ValueError("offline facts catalog contains self-attributed content")
        key = (" ".join(title.casefold().split()), " ".join(body.casefold().split()))
        if key in seen:
            raise ValueError("offline facts catalog contains duplicate entries")
        seen.add(key)
        normalized.append((title, body, attribution))
    if len(normalized) < minimum:
        raise ValueError(f"offline facts catalog must contain at least {minimum} unique entries")
    return tuple(normalized)


def load_offline_facts(path: str | os.PathLike[str] | None = None) -> tuple[tuple[str, str, str], ...]:
    """Load the source/frozen catalog, falling back safely on any failure."""

    candidates = (Path(path),) if path else _catalog_candidates()
    for candidate in candidates:
        try:
            if not candidate.is_file():
                continue
            payload = json.loads(candidate.read_text(encoding="utf-8"))
            return validate_catalog(payload)
        except (OSError, UnicodeError, json.JSONDecodeError, TypeError, ValueError):
            continue
    return _FALLBACK_FACTS


OFFLINE_FACTS = load_offline_facts()

__all__ = [
    "OFFLINE_FACTS",
    "load_offline_facts",
    "validate_catalog",
]
